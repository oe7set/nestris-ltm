export type Locale = "de" | "en";
const catalogs: Record<Locale, Record<MessageKey, string>> = { de, en };
const STORAGE_KEY = "nltm.locale";

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "de" || stored === "en") return stored;
  } catch {
    // storage blocked: fall back to the default
  }
  return "de";
}

class I18n {
  locale = $state<Locale>(initialLocale());

  set(locale: Locale): void {
    this.locale = locale;
    document.documentElement.lang = locale;
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // ignore
    }
  }
}

export const i18n = new I18n();

export function format(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match,
  );
}

/** Translate; reactive because it reads ``i18n.locale``. */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  return format(catalogs[i18n.locale][key], params);
}

/** For keys built at runtime (e.g. "games.status." + value); falls back to the raw value. */
export function tDynamic(key: string, fallback: string): string {
  const catalog = catalogs[i18n.locale] as Record<string, string>;
  return catalog[key] ?? fallback;
}
